// Convert object {0: value, 1: value, ...} to Uint8Array
function objectToUint8Array(obj) {
    // Find the highest index to determine array length
    let maxIndex = -1;
    for (const key in obj) {
        if (obj.hasOwnProperty(key)) {
            const index = parseInt(key);
            if (index > maxIndex) maxIndex = index;
        }
    }

    if (maxIndex === -1) return new Uint8Array(0);

    const array = new Uint8Array(maxIndex + 1);

    for (const [key, value] of Object.entries(obj)) {
        const index = parseInt(key);
        if (!isNaN(index) && index >= 0 && index <= maxIndex) {
            array[index] = value;
        }
    }

    return array;
}

class BinaryDecoder {
    constructor(buffer) {
        this.buffer = buffer;
        this.offset = 0;
    }

    // Read a byte
    readByte() {
        if (this.offset >= this.buffer.length) {
            throw new Error("Buffer overflow");
        }
        return this.buffer[this.offset++];
    }

    // Read 16-bit big-endian integer
    readUint16BE() {
        const b1 = this.readByte();
        const b2 = this.readByte();
        return (b1 << 8) | b2;
    }

    // Read 32-bit big-endian integer
    readUint32BE() {
        const b1 = this.readByte();
        const b2 = this.readByte();
        const b3 = this.readByte();
        const b4 = this.readByte();
        return (b1 << 24) | (b2 << 16) | (b3 << 8) | b4;
    }

    // Read float32 (big-endian)
    readFloat32() {
        const bytes = new Uint8Array([
            this.readByte(), this.readByte(),
            this.readByte(), this.readByte()
        ]);
        return new DataView(bytes.buffer).getFloat32(0, false); // false = big-endian
    }

    // Read float64 (big-endian)
    readFloat64() {
        const bytes = new Uint8Array([
            this.readByte(), this.readByte(), this.readByte(), this.readByte(),
            this.readByte(), this.readByte(), this.readByte(), this.readByte()
        ]);
        return new DataView(bytes.buffer).getFloat64(0, false); // false = big-endian
    }

    // Read variable-length string
    readString(length) {
        let result = '';
        for (let i = 0; i < length; i++) {
            result += String.fromCharCode(this.readByte());
        }
        return result;
    }

    // Read binary data
    readBinary(length) {
        const start = this.offset;
        this.offset += length;
        return this.buffer.slice(start, start + length);
    }

    // Read length prefix
    readLength() {
        const firstByte = this.readByte();

        if (firstByte < 0xC0) {
            // Fixstr: 101XXXXX (0xA0-0xBF)
            if (firstByte >= 0xA0 && firstByte <= 0xBF) {
                const length = firstByte & 0x1F; // Lower 5 bits
                return this.readString(length);
            }
            // Positive fixint: 0XXXXXXX (0x00-0x7F)
            else if (firstByte <= 0x7F) {
                return firstByte;
            }
            // Negative fixint: 111XXXXX (0xE0-0xFF)
            else if (firstByte >= 0xE0) {
                return firstByte - 256; // Convert to signed
            }
            // Fixarray: 1001XXXX (0x90-0x9F)
            else if (firstByte >= 0x90 && firstByte <= 0x9F) {
                return this.readArray(firstByte & 0x0F);
            }
            // Fixmap: 1000XXXX (0x80-0x8F)
            else if (firstByte >= 0x80 && firstByte <= 0x8F) {
                return this.readMap(firstByte & 0x0F);
            }
        }

        switch (firstByte) {
            case 0xC0: // nil
                return null;
            case 0xC2: // false
                return false;
            case 0xC3: // true
                return true;
            case 0xC4: // bin8
                return this.readBinary(this.readByte());
            case 0xC5: // bin16
                return this.readBinary(this.readUint16BE());
            case 0xC6: // bin32
                return this.readBinary(this.readUint32BE());
            case 0xCA: // float32
                return this.readFloat32();
            case 0xCB: // float64
                return this.readFloat64();
            case 0xCC: // uint8
                return this.readByte();
            case 0xCD: // uint16
                return this.readUint16BE();
            case 0xCE: // uint32
                return this.readUint32BE();
            case 0xCF: // uint64 (simplified as Number)
                const high = this.readUint32BE();
                const low = this.readUint32BE();
                return (high * 0x100000000) + low;
            case 0xD0: // int8
                const b = this.readByte();
                return b > 127 ? b - 256 : b;
            case 0xD1: // int16
                const val = this.readUint16BE();
                return val > 32767 ? val - 65536 : val;
            case 0xD2: // int32
                const int32 = this.readUint32BE();
                return int32 > 2147483647 ? int32 - 4294967296 : int32;
            case 0xD3: // int64 (simplified as Number)
                const highInt = this.readUint32BE();
                const lowInt = this.readUint32BE();
                const int64 = (highInt * 0x100000000) + lowInt;
                return int64 > 9223372036854775807 ? int64 - 18446744073709551616 : int64;
            case 0xD9: // str8
                return this.readString(this.readByte());
            case 0xDA: // str16
                return this.readString(this.readUint16BE());
            case 0xDB: // str32
                return this.readString(this.readUint32BE());
            case 0xDC: // array16
                return this.readArray(this.readUint16BE());
            case 0xDD: // array32
                return this.readArray(this.readUint32BE());
            case 0xDE: // map16
                return this.readMap(this.readUint16BE());
            case 0xDF: // map32
                return this.readMap(this.readUint32BE());
            case 0xC7: // ext8 (ignore)
            case 0xC8: // ext16 (ignore)
            case 0xC9: // ext32 (ignore)
                const extLength = firstByte === 0xC7 ? this.readByte() :
                    firstByte === 0xC8 ? this.readUint16BE() : this.readUint32BE();
                const type = this.readByte();
                this.offset += extLength; // Skip extension data
                return { type, length: extLength };
            default:
                throw new Error(`Unknown format: 0x${firstByte.toString(16).padStart(2, '0')} at offset ${this.offset - 1}`);
        }
    }

    // Read array
    readArray(length) {
        const arr = new Array(length);
        for (let i = 0; i < length; i++) {
            arr[i] = this.decode();
        }
        return arr;
    }

    // Read map/dictionary
    readMap(length) {
        const obj = {};
        for (let i = 0; i < length; i++) {
            const key = this.decode();
            const value = this.decode();
            obj[key] = value;
        }
        return obj;
    }

    // Main decode function
    decode() {
        return this.readLength();
    }

    // Helper to decode entire buffer
    decodeAll() {
        const result = [];
        while (this.offset < this.buffer.length) {
            result.push(this.decode());
        }
        return result.length === 1 ? result[0] : result;
    }
}

// Main decode function
function decodeHCaptchaBuffer(uint8Array) {
    const decoder = new BinaryDecoder(uint8Array);
    try {
        return decoder.decodeAll();
    } catch (error) {
        console.error("Decoding error:", error);
        console.error("Offset:", decoder.offset, "Buffer length:", uint8Array.length);
        return null;
    }
}

